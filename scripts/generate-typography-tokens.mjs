import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { webLightTheme } from '@fluentui/react-theme';

const outputUrl = new URL('../src/styles/typography-tokens.css', import.meta.url);
const checkOnly = process.argv.includes('--check');
const tokenNames = [
  'fontFamilyBase',
  'fontFamilyMonospace',
  'fontFamilyNumeric',
  'fontSizeBase100',
  'fontSizeBase200',
  'fontSizeBase300',
  'fontSizeBase400',
  'fontSizeBase500',
  'fontSizeBase600',
  'fontSizeHero700',
  'fontSizeHero800',
  'fontSizeHero900',
  'fontSizeHero1000',
  'fontWeightRegular',
  'fontWeightMedium',
  'fontWeightSemibold',
  'fontWeightBold',
  'lineHeightBase100',
  'lineHeightBase200',
  'lineHeightBase300',
  'lineHeightBase400',
  'lineHeightBase500',
  'lineHeightBase600',
  'lineHeightHero700',
  'lineHeightHero800',
  'lineHeightHero900',
  'lineHeightHero1000',
].sort();

function toCssVariable(tokenName) {
  return `--fui-${tokenName
    .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
    .replace(/([A-Za-z])(\d)/g, '$1-$2')
    .toLowerCase()}`;
}

function generateCss() {
  const declarations = tokenNames.map(tokenName => {
    const value = webLightTheme[tokenName];

    if (value === undefined) {
      throw new Error(`Missing Fluent typography token: ${tokenName}`);
    }

    return `  ${toCssVariable(tokenName)}: ${value};`;
  });

  return `/* Generated by scripts/generate-typography-tokens.mjs.\n * Source: @fluentui/react-theme@9.2.2 (webLightTheme)\n * Do not edit manually.\n */\n:root,\n.fui-theme-light,\n.fui-theme-dark {\n${declarations.join('\n')}\n}\n`;
}

const generatedCss = generateCss();

if (checkOnly) {
  const currentCss = await readFile(outputUrl, 'utf8').catch(() => '');

  if (currentCss !== generatedCss) {
    console.error(`${fileURLToPath(outputUrl)} is stale. Run npm run tokens:generate.`);
    process.exitCode = 1;
  }
} else {
  await writeFile(outputUrl, generatedCss);
}
