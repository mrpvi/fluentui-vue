import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { webDarkTheme, webLightTheme } from '@fluentui/react-theme';

const outputUrl = new URL('../src/styles/tokens.css', import.meta.url);
const checkOnly = process.argv.includes('--check');
const tokenNames = Object.keys(webLightTheme).sort();
const darkTokenNames = Object.keys(webDarkTheme).sort();

if (JSON.stringify(tokenNames) !== JSON.stringify(darkTokenNames)) {
  throw new Error('Fluent light and dark themes expose different token sets.');
}

if (tokenNames.length !== 459) {
  throw new Error(`Expected 459 Fluent theme tokens, received ${tokenNames.length}.`);
}

function toCssVariable(tokenName) {
  return `--fui-${tokenName
    .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
    .replace(/([A-Z])([A-Z][a-z])/g, '$1-$2')
    .replace(/([A-Za-z])(\d)/g, '$1-$2')
    .toLowerCase()}`;
}

function declarations(theme, names) {
  return names.map((tokenName) => {
    const value = theme[tokenName];

    if (value === undefined) {
      throw new Error(`Missing Fluent theme token: ${tokenName}`);
    }

    return `  ${toCssVariable(tokenName)}: ${value};`;
  });
}

function generateCss() {
  const invariantTokenNames = tokenNames.filter(
    (tokenName) => webLightTheme[tokenName] === webDarkTheme[tokenName],
  );
  const variantTokenNames = tokenNames.filter(
    (tokenName) => webLightTheme[tokenName] !== webDarkTheme[tokenName],
  );

  return `/* Generated by scripts/generate-theme-tokens.mjs.
 * Source: @fluentui/react-theme@9.2.2 (webLightTheme and webDarkTheme)
 * Tokens: ${tokenNames.length} total; ${invariantTokenNames.length} invariant; ${variantTokenNames.length} theme-specific.
 * Do not edit manually.
 */
:root,
.fui-theme-light,
.fui-theme-dark {
${declarations(webLightTheme, invariantTokenNames).join('\n')}
}

:root,
.fui-theme-light {
${declarations(webLightTheme, variantTokenNames).join('\n')}
}

.fui-theme-dark {
${declarations(webDarkTheme, variantTokenNames).join('\n')}
}
`;
}

const generatedCss = generateCss();

if (checkOnly) {
  const currentCss = await readFile(outputUrl, 'utf8').catch(() => '');

  if (currentCss !== generatedCss) {
    console.error(`${fileURLToPath(outputUrl)} is stale. Run npm run tokens:generate.`);
    process.exitCode = 1;
  }
} else {
  await writeFile(outputUrl, generatedCss);
}
